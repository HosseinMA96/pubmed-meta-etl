"""Collects every configured run into RESULTS.md (status, config, metrics).

Reads only config.json, runs/*.json and batch_log.txt, so it is safe to run while
the batch is still going. Re-run it after every batch: python3 -I summarize.py
"""
import json
import os
import re
import time

HERE = os.path.dirname(os.path.abspath(__file__))
cfg = json.load(open(os.path.join(HERE, "config.json")))
log = open(os.path.join(HERE, "batch_log.txt")).read() if os.path.exists(os.path.join(HERE, "batch_log.txt")) else ""

started = set(re.findall(r"start (\S+)", log))
ended = set(re.findall(r"end (\S+)", log))
killed = set(re.findall(r"Killed.*?\n\d\d:\d\d:\d\d end (\S+)", log)) | set(re.findall(r"end (\S+) FAILED", log))


def status(name):
    if os.path.exists(os.path.join(HERE, "runs", f"{name}.json")):
        return "done"
    if name in killed:
        return "KILLED or FAILED (see logs)"
    if name in ended:
        return "FAILED (no JSON)"
    if name in started:
        return "running"
    return "pending"


def fmt(x, nd=2):
    return f"{x:,.{nd}f}" if isinstance(x, float) else f"{x:,}" if isinstance(x, int) else str(x)


rows, done = [], {}
for name, run in cfg["runs"].items():
    st = status(name)
    p = os.path.join(HERE, "runs", f"{name}.json")
    if st == "done":
        done[name] = d = json.load(open(p))
        ci = d["coherence_intra"]
        rows.append([name, run["setting"], run.get("transform", "raw") + (f"+{run['misalign']}" if run.get("misalign") else ""), run["seed"], st,
                     fmt(d["mean_weight_raw"], 5), fmt(d["predicted_effective_gamma"], 4),
                     fmt(d["cov1"]), fmt(d["cov10"]), fmt(d["clusters_gt1"]), fmt(d["clusters_gt10"]),
                     fmt(d["singletons"]), fmt(d["max_size"]), fmt(round(d["cpm_score_unweighted_0.05"])),
                     fmt(d["intra_edge_share"], 3), fmt(ci["mean_f6"], 4), fmt(ci["share_within_5y"], 3),
                     fmt(ci["mean_bib_jaccard"], 4), fmt(d["peak_rss_gb"], 1), fmt(round(d["cluster_seconds"]))])
    else:
        rows.append([name, run["setting"], run.get("transform", "raw") + (f"+{run['misalign']}" if run.get("misalign") else ""), run["seed"], st] + [""] * 15)

hdr = ["run", "setting", "transform", "seed", "status", "mean w (raw)", "pred. eff. γ", "Cov1 %", "Cov10 %",
       "clusters>1", "clusters>10", "singletons", "max size", "CPM (unw., γ=0.05)", "intra-edge share",
       "intra mean f6", "intra share |ΔY|≤5", "intra mean bibJ", "peak RSS GB", "cluster s"]

out = [f"# Scale test: results table (auto-generated by summarize.py, {time.strftime('%Y-%m-%d %H:%M')})", "",
       "New experiments, not in the thesis. Do not edit by hand; see RESULTS_LOG.md for the narrative.", "",
       f"Engine: {cfg.get('engine')}; γ = {cfg['gamma']}; weight order: {cfg['weight_order']}.", "",
       "## Settings (coefficients in thesis order)", ""]
for s, c in cfg["settings"].items():
    out.append(f"- `{s}`: {'none (unweighted)' if c is None else [round(x, 4) for x in c]}")
out += ["", "## All runs", "", "| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)]
out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]

# Seed spread per (setting, transform) for finished runs
groups = {}
for name, d in done.items():
    groups.setdefault((d["setting"], d["transform"] + (f"+{d['misalign']}" if d.get("misalign") else "") + ("" if d["run"] != "baseline_s4311_repeat" else "+repeat")), []).append(d)
out += ["", "## Seed spread (finished runs only; sd is sample sd, n = number of seeds)", "",
        "| setting | transform | n | Cov1 mean ± sd | Cov10 mean ± sd | CPM mean ± sd |", "|---|---|---|---|---|---|"]
for (s, t), ds in sorted(groups.items()):
    def ms(key):
        xs = [d[key] for d in ds]
        m = sum(xs) / len(xs)
        sd = (sum((x - m) ** 2 for x in xs) / (len(xs) - 1)) ** 0.5 if len(xs) > 1 else float("nan")
        return f"{m:,.2f} ± {sd:,.2f}"
    out.append(f"| {s} | {t} | {len(ds)} | {ms('cov1')} | {ms('cov10')} | {ms('cpm_score_unweighted_0.05')} |")

open(os.path.join(HERE, "RESULTS.md"), "w").write("\n".join(out) + "\n")
print(f"{len(done)} done / {len(cfg['runs'])} configured -> RESULTS.md")

# Run manifest: one row per configured run with its provenance (what ran, when, with which script)
import csv
import hashlib

V1_SHA = hashlib.sha256(open(os.path.join(HERE, "run_cpm_v1.py"), "rb").read()).hexdigest()
_v2 = os.path.join(HERE, "run_cpm_v2.py")
V2_SHA = hashlib.sha256(open(_v2, "rb").read()).hexdigest() if os.path.exists(_v2) else "42fd41552cb74ab094ae80b8cf7b46a30f59e095bab3315eae87cbc74da2df11"
_v3 = os.path.join(HERE, "run_cpm_v3.py")
V3_SHA = hashlib.sha256(open(_v3, "rb").read()).hexdigest() if os.path.exists(_v3) else ""
CUR_SHA = hashlib.sha256(open(os.path.join(HERE, "run_cpm.py"), "rb").read()).hexdigest()
times = {}
for line in log.splitlines():
    m = re.match(r"(\d\d:\d\d:\d\d) (start|end) (\S+)(.*)", line)
    if m:
        info = m.group(4).strip().strip("()")
        rec = times.setdefault(m.group(3), {"attempts": 0})
        rec[m.group(2)] = m.group(1) + (f" [{info}]" if info else "")
        rec["attempts"] += m.group(2) == "start"
with open(os.path.join(HERE, "runs_manifest.csv"), "w", newline="") as fh:
    wr = csv.writer(fh)
    wr.writerow(["run", "status", "config_entry", "attempts", "last_log_start", "last_log_end", "json_written", "script_sha256",
                 "script_version", "json_sha256", "peak_rss_gb", "cluster_seconds"])
    for name, run in cfg["runs"].items():
        p = os.path.join(HERE, "runs", f"{name}.json")
        t = times.get(name, {})
        row = [name, status(name), json.dumps(run, sort_keys=True),
               t.get("attempts", "feasibility run, see feasibility_log.txt" if name == "baseline_s4311" else 0),
               t.get("start", ""), t.get("end", "")]
        if os.path.exists(p):
            d = json.load(open(p))
            sha = d.get("script_sha256", V1_SHA)
            row += [time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(os.path.getmtime(p))), sha,
                    {V1_SHA: "v1 (run_cpm_v1.py)", V2_SHA: "v2 (run_cpm_v2.py)", V3_SHA: "v3 (run_cpm_v3.py)"}.get(sha, "current run_cpm.py" if sha == CUR_SHA else "other (see RESULTS_LOG)"),
                    hashlib.sha256(open(p, "rb").read()).hexdigest(), f"{d['peak_rss_gb']:.2f}", f"{d['cluster_seconds']:.0f}"]
        else:
            row += [""] * 6
        wr.writerow(row)
print("-> runs_manifest.csv")
